var updateInventory = flag.Bool("update-hosted-inventory", false, "rewrite the hosted-only inventory in docs/reports/freestanding-availability.md")

const (
	inventoryReport = "../../docs/reports/freestanding-availability.md"
	inventoryBegin  = "<!-- hosted-only inventory: generated by TestHostedOnlyInventory -->"
	inventoryEnd    = "<!-- end of the hosted-only inventory -->"
)

// corpusUnits are the programs of specs/freestanding-availability R7: one
// per file under bench/kern/*/, tests/run, tests/trap and tests/positive,
// one per examples/ directory (a project when it has a manifest, else
// each file), and one per agent-suite reference directory.
func corpusUnits(t *testing.T) [][]string {
	t.Helper()
	root := filepath.Join("..", "..")
	glob := func(pat string) []string {
		m, err := filepath.Glob(filepath.Join(root, pat))
		if err != nil {
			t.Fatal(err)
		}
		sort.Strings(m)
		return m
	}
	var units [][]string
	for _, pat := range []string{"bench/kern/*/*.kern", "tests/run/*.kern", "tests/trap/*.kern", "tests/positive/*.kern"} {
		for _, f := range glob(pat) {
			if !strings.HasSuffix(f, "_test.kern") {
				units = append(units, []string{f})
			}
		}
	}
	for _, d := range glob("examples/*") {
		var files []string
		_ = filepath.WalkDir(d, func(p string, e os.DirEntry, err error) error {
			if err == nil && !e.IsDir() && strings.HasSuffix(p, ".kern") && !strings.HasSuffix(p, "_test.kern") {
				files = append(files, p)
			}
			return nil
		})
		sort.Strings(files)
		if _, err := os.Stat(filepath.Join(d, project.ManifestName)); err == nil {
			units = append(units, files)
		} else {
			for _, f := range files {
				units = append(units, []string{f})
			}
		}
	}
	for _, d := range glob("bench/agent/tasks*/t*/reference") {
		if files := glob(filepath.Join(strings.TrimPrefix(d, root+string(filepath.Separator)), "*.kern")); len(files) > 0 {
			units = append(units, files)
		}
	}
	return units
}

// inventory is the hosted-only entries each library function the corpus
// compiles reaches, per target, rendered as the report's list.
func inventory(t *testing.T) string {
	t.Helper()
	cwd, _ := os.Getwd()
	targets := []string{"aarch64-unknown-none-elf", "x86_64-unknown-none-elf"}
	per := map[string]map[string][]string{}
	units := corpusUnits(t)
	lowered := 0
	for _, u := range units {
		pr := project.Load(cwd, u)
		if len(pr.Diags) > 0 {
			continue
		}
		prog := resolve.Resolve(pr.Files)
		if len(prog.Diags) > 0 || len(check.Check(prog)) > 0 {
			continue
		}
		mod, ds := lower.Lower(prog)
		if len(ds) > 0 || opt.Run(mod, opt.OptionsFor("debug")) != nil {
			continue
		}
		lowered++
		for _, tr := range targets {
			res, err := analysis.HostedOnly(mod, tr)
			if err != nil {
				t.Fatalf("%v %s: %v", u, tr, err)
			}
			if per[tr] == nil {
				per[tr] = map[string][]string{}
			}
			for f, es := range res.Library {
				per[tr][f] = mergeSorted(per[tr][f], es)
			}
		}
	}
	if lowered < 200 {
		t.Fatalf("only %d of %d corpus programs lowered", lowered, len(units))
	}
	var b strings.Builder
	render := func(m map[string][]string) {
		names := make([]string, 0, len(m))
		for n := range m {
			names = append(names, n)
		}
		sort.Strings(names)
		b.WriteString("| library function | hosted-only entries it reaches |\n|---|---|\n")
		for _, n := range names {
			fmt.Fprintf(&b, "| `%s` | `%s` |\n", n, strings.Join(m[n], "`, `"))
		}
	}
	fmt.Fprintf(&b, "%d of %d corpus programs lowered, at `--opt=debug`.\n\n", lowered, len(units))
	if reflect.DeepEqual(per[targets[0]], per[targets[1]]) {
		b.WriteString("The two freestanding targets give the same list.\n\n")
		render(per[targets[0]])
	} else {
		for _, tr := range targets {
			fmt.Fprintf(&b, "`%s`:\n\n", tr)
			render(per[tr])
			b.WriteString("\n")
		}
	}
	return b.String()
}

func mergeSorted(a, b []string) []string {
	m := map[string]bool{}
	for _, s := range append(append([]string{}, a...), b...) {
		m[s] = true
	}
	out := make([]string, 0, len(m))
	for s := range m {
		out = append(out, s)
	}
	sort.Strings(out)
	return out
}

// The report's inventory is the one the analysis gives over the corpus
// (R7); -update-hosted-inventory rewrites it.
func TestHostedOnlyInventory(t *testing.T) {
	got := inventory(t)
	b, err := os.ReadFile(inventoryReport)
	if err != nil {
		t.Fatal(err)
	}
	s := string(b)
	i, j := strings.Index(s, inventoryBegin), strings.Index(s, inventoryEnd)
	if i < 0 || j < i {
		t.Fatalf("%s has no inventory markers", inventoryReport)
	}
	cur := s[i+len(inventoryBegin)+1 : j]
	if cur == got {
		return
	}
	if !*updateInventory {
		t.Fatalf("the report's inventory is stale; run go test ./compiler/analysis -run TestHostedOnlyInventory -update-hosted-inventory\n%s", got)
	}
	s = s[:i+len(inventoryBegin)+1] + got + s[j:]
	if err := os.WriteFile(inventoryReport, []byte(s), 0o644); err != nil {
		t.Fatal(err)
	}
}
