package main

import (
	"fmt"
	"sort"
	"strings"
	"time"
)

// writeAgentReport renders bench/agent/REPORT.md: the win count out of ten
// with the per-task medians, trial counts and models (PLAN.md 4.2).
func writeAgentReport(records []trialRecord, tasks []*task, trials, iterations int, budget time.Duration) string {
	var b strings.Builder
	b.WriteString("# Agent experiment report\n\n")
	fmt.Fprintf(&b, "Generated by `go run ./bench/agent/harness` (PLAN.md 4.2, spec §9). Date: %s. Budgets: %d iterations, %s wall-clock per trial; a failed or timed-out trial scores the budget maximum for both. A task is a **win** when, for every model, the structured arm has at least as many successful trials and a strictly lower median iteration count and a strictly lower median wall-clock time than the plain arm (ties lose). The primary metric passes at 8 wins of 10.\n\n", time.Now().Format("2006-01-02"), iterations, budget)
	models := map[string]bool{}
	for _, r := range records {
		models[r.Model] = true
	}
	var modelList []string
	for m := range models {
		modelList = append(modelList, m)
	}
	sort.Strings(modelList)
	fmt.Fprintf(&b, "Models: %s. Trials per task, model and arm: %d. Arms: `structured` (JSON diagnostics with rule numbers plus `explain_ownership`, `show_copies`, `show_allocations`) and `plain` (text diagnostics only); both arms receive the same language reference, grammar, prelude and examples.\n\n", strings.Join(modelList, ", "), trials)
	type cell struct {
		n, successes          int
		iters, wall, tokens   []float64
		regressions, unsafeNB int
	}
	cells := map[string]*cell{} // task|model|arm
	key := func(t, m, a string) string { return t + "|" + m + "|" + a }
	for _, r := range records {
		c := cells[key(r.Task, r.Model, r.Arm)]
		if c == nil {
			c = &cell{}
			cells[key(r.Task, r.Model, r.Arm)] = c
		}
		c.n++
		if r.Success {
			c.successes++
		}
		c.iters = append(c.iters, float64(r.Iterations))
		c.wall = append(c.wall, r.WallSeconds)
		c.tokens = append(c.tokens, float64(r.InputTokens+r.OutputTok))
		c.regressions += r.Regressions
		c.unsafeNB += r.UnsafeAdded
	}
	wins := 0
	b.WriteString("## Per-task results\n\n| task | kind | model | arm | trials | successes | median iterations | median wall (s) | median tokens | regressions | unsafe lines added |\n|---|---|---|---|---|---|---|---|---|---|---|\n")
	for _, t := range tasks {
		win := len(modelList) > 0
		for _, m := range modelList {
			s, p := cells[key(t.Name, m, "structured")], cells[key(t.Name, m, "plain")]
			for _, arm := range []string{"structured", "plain"} {
				c := cells[key(t.Name, m, arm)]
				if c == nil {
					fmt.Fprintf(&b, "| %s | %s | %s | %s | 0 | | | | | | |\n", t.Name, t.Kind, m, arm)
					continue
				}
				fmt.Fprintf(&b, "| %s | %s | %s | %s | %d | %d | %.1f | %.0f | %.0f | %d | %d |\n", t.Name, t.Kind, m, arm, c.n, c.successes, median(c.iters), median(c.wall), median(c.tokens), c.regressions, c.unsafeNB)
			}
			if s == nil || p == nil || s.n < 5 || p.n < 5 || s.successes < p.successes || !(median(s.iters) < median(p.iters)) || !(median(s.wall) < median(p.wall)) {
				win = false
			}
		}
		if win {
			wins++
		}
		fmt.Fprintf(&b, "| %s | | | **%s** | | | | | | | |\n", t.Name, map[bool]string{true: "win", false: "loss"}[win])
	}
	fmt.Fprintf(&b, "\n## Primary metric\n\n**%d wins of %d tasks**", wins, len(tasks))
	if len(tasks) == 10 {
		fmt.Fprintf(&b, " — the primary metric %s (threshold 8 of 10).", map[bool]string{true: "passes", false: "does not pass"}[wins >= 8])
	}
	b.WriteString("\n\nA task with fewer than 5 trials per arm for any model is a loss by definition (insufficient trials), so partial runs report conservatively.\n\n")
	b.WriteString("## Secondary comparison (descriptive only)\n\nNo Go or Rust arm was run. Any comparison with Go or Rust agents would be confounded by training data: both languages are abundantly represented in model training corpora while kern is not, so a difference in either direction would not isolate the effect of structured diagnostics. The within-kern ablation above is the only controlled comparison in this report.\n")
	return b.String()
}
